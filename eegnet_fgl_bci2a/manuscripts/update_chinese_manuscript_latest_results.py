def latest_data() -> dict[str, pd.DataFrame]:
    old_runs = pd.read_csv(
        ROOT / "results" / "global_routing_multiseed" / "all_subject_seed_results.csv"
    )
    runs_2a = old_runs[old_runs["dataset"] == "bci2a"].copy()
    runs_2b = pd.read_csv(
        ROOT
        / "results"
        / "global_routing_multiseed_unified"
        / "bci2b_subject_seed_results.csv"
    )
    runs = pd.concat([runs_2a, runs_2b], ignore_index=True, sort=False)
    subject_means = runs.groupby(["dataset", "subject"], as_index=False).mean(
        numeric_only=True
    )
    selection = (
        runs.groupby(["dataset", "global_selected"], as_index=False)
        .size()
        .rename(columns={"size": "count"})
    )
    old = original_load_data()
    old["runs"] = runs
    old["subject_means"] = subject_means
    old["selection"] = selection
    return old


zh.load_data = latest_data


